"""Own windowed-sinc FIR design; no external tables or copyrighted DSP data.
129 taps on the common 96 kHz nominal interpolation grid, Kaiser beta=8,
cutoff=0.15 cycles/grid-sample (14.4 kHz nominal; 14.0625 kHz at shell rate).
Each polyphase branch is normalized for unity DC. float32 rounding is explicit.
"""
from pathlib import Path
import math,struct,json

def bessel_i0(x):
 total=term=1.0
 for k in range(1,100):
  term*=x*x/(4*k*k);total+=term
  if term<total*1e-16:break
 return total

def prototype():
 length=129;cutoff=.15;beta=8.0;den=bessel_i0(beta)
 values=[]
 for i in range(length):
  x=i-(length-1)/2
  sinc=2*cutoff if x==0 else math.sin(2*math.pi*cutoff*x)/(math.pi*x)
  win=bessel_i0(beta*math.sqrt(max(0,1-(x/64)**2)))/den
  values.append(sinc*win)
 return values

def phases(up):
 h=prototype();count=(len(h)+up-1)//up;out=[]
 for p in range(up):
  raw=[h[p+up*k] if p+up*k<len(h) else 0 for k in range(count)];norm=sum(raw)
  out.append([struct.unpack('<f',struct.pack('<f',x/norm))[0] for x in raw])
 return out

def render():
 text=['/* Generated by generate_cold_coefficients.py; windowed-sinc Kaiser FIR. */']
 for name,up in [('cold_down_coeff',2),('cold_up_coeff',3)]:
  a=phases(up);text.append(f'static const float {name}[{up}][{len(a[0])}] = {{')
  for row in a:text.append(' {'+', '.join(float(x).hex()+'f' for x in row)+'},')
  text.append('};')
 return '\n'.join(text)+'\n'
if __name__=='__main__':
 Path(__file__).with_name('cold_coefficients.h').write_text(render())
